// 言語検出
function detectLang(){
  const lang = navigator.language || navigator.userLanguage || "ja";
  const code = lang.toLowerCase().split("-")[0];
  if(code === "ja") return "ja";
  if(code === "ko") return "ko";
  if(code === "zh") return "zh";
  if(code === "de") return "de";
  if(code === "es") return "es";
  return "en"; // デフォルトは英語
}

